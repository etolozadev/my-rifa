-- mis-rifas · esquema PostgreSQL (fuente de verdad de la estructura)
-- Se ejecuta con: npm run db:init   (es idempotente: usa IF NOT EXISTS)

CREATE TABLE IF NOT EXISTS users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        TEXT        NOT NULL,
  email         TEXT        NOT NULL,
  password_hash TEXT        NOT NULL,
  creado_en     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_uq ON users (lower(email));

CREATE TABLE IF NOT EXISTS raffles (
  id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug                   TEXT        NOT NULL UNIQUE,
  nombre                 TEXT        NOT NULL,
  proposito              TEXT        NOT NULL DEFAULT 'otro'
                         CHECK (proposito IN ('beneficio', 'viaje', 'otro')),
  objetivo               TEXT        NOT NULL DEFAULT '',
  meta_monto             INTEGER     NOT NULL DEFAULT 0 CHECK (meta_monto >= 0),
  precio_numero          INTEGER     NOT NULL CHECK (precio_numero > 0),
  cantidad_talonarios    INTEGER     NOT NULL CHECK (cantidad_talonarios BETWEEN 1 AND 500),
  numeros_por_talonario  INTEGER     NOT NULL CHECK (numeros_por_talonario BETWEEN 1 AND 200),
  max_numeros_por_orden  INTEGER     NOT NULL DEFAULT 20 CHECK (max_numeros_por_orden > 0),
  ttl_reserva_dias       INTEGER     NOT NULL DEFAULT 7 CHECK (ttl_reserva_dias > 0),
  fecha_sorteo           TIMESTAMPTZ NOT NULL,
  estado                 TEXT        NOT NULL DEFAULT 'borrador'
                         CHECK (estado IN ('borrador', 'activa', 'cerrada', 'sorteada')),
  -- Datos bancarios (una sola cuenta por rifa)
  banco_nombre           TEXT,
  banco_tipo_cuenta      TEXT,
  banco_numero_cuenta    TEXT,
  banco_titular          TEXT,
  banco_rut              TEXT,
  banco_email_aviso      TEXT,
  numero_autorizacion    TEXT,
  creado_en              TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS raffle_members (
  raffle_id INTEGER NOT NULL REFERENCES raffles (id) ON DELETE CASCADE,
  user_id   INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  rol       TEXT    NOT NULL CHECK (rol IN ('organizador', 'editor', 'vendedor')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (raffle_id, user_id)
);

CREATE TABLE IF NOT EXISTS booklets (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raffle_id INTEGER NOT NULL REFERENCES raffles (id) ON DELETE CASCADE,
  numero    INTEGER NOT NULL CHECK (numero > 0),
  UNIQUE (raffle_id, numero)
);

-- Vendedores (fase 2: se crea la tabla ahora para no migrar después)
CREATE TABLE IF NOT EXISTS sellers (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raffle_id     INTEGER NOT NULL REFERENCES raffles (id) ON DELETE CASCADE,
  user_id       INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  codigo_enlace TEXT    NOT NULL UNIQUE,
  UNIQUE (raffle_id, user_id)
);

CREATE TABLE IF NOT EXISTS orders (
  id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raffle_id            INTEGER     NOT NULL REFERENCES raffles (id) ON DELETE CASCADE,
  token                TEXT        NOT NULL UNIQUE,
  tipo                 TEXT        NOT NULL CHECK (tipo IN ('numeros', 'talonario')),
  canal                TEXT        NOT NULL DEFAULT 'web' CHECK (canal IN ('web', 'fisica', 'manual')),
  comprador_nombre     TEXT        NOT NULL,
  comprador_contacto   TEXT        NOT NULL,
  seller_id            INTEGER     REFERENCES sellers (id) ON DELETE SET NULL,
  -- Números pedidos: se conservan aunque la orden venza (historial y reactivación)
  numeros              INTEGER[]   NOT NULL CHECK (cardinality(numeros) > 0),
  monto                INTEGER     NOT NULL CHECK (monto > 0),
  estado               TEXT        NOT NULL DEFAULT 'pendiente'
                       CHECK (estado IN ('pendiente', 'pagada', 'vencida', 'cancelada')),
  creada_en            TIMESTAMPTZ NOT NULL DEFAULT now(),
  vence_en             TIMESTAMPTZ NOT NULL,
  pagada_en            TIMESTAMPTZ,
  confirmada_por       INTEGER     REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS orders_raffle_estado_idx ON orders (raffle_id, estado);
CREATE INDEX IF NOT EXISTS orders_vencimiento_idx ON orders (vence_en) WHERE estado = 'pendiente';

CREATE TABLE IF NOT EXISTS tickets (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raffle_id  INTEGER NOT NULL REFERENCES raffles (id) ON DELETE CASCADE,
  booklet_id INTEGER NOT NULL REFERENCES booklets (id) ON DELETE CASCADE,
  numero     INTEGER NOT NULL CHECK (numero > 0),
  estado     TEXT    NOT NULL DEFAULT 'disponible'
             CHECK (estado IN ('disponible', 'reservado', 'pagado')),
  order_id   INTEGER REFERENCES orders (id) ON DELETE SET NULL,
  seller_id  INTEGER REFERENCES sellers (id) ON DELETE SET NULL,
  -- Un número solo existe una vez por rifa: evita la doble venta a nivel de base
  UNIQUE (raffle_id, numero),
  -- Coherencia: un número disponible no tiene orden; uno ocupado sí
  CHECK ((estado = 'disponible' AND order_id IS NULL) OR (estado <> 'disponible' AND order_id IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS tickets_order_idx ON tickets (order_id);
CREATE INDEX IF NOT EXISTS tickets_raffle_estado_idx ON tickets (raffle_id, estado);
CREATE INDEX IF NOT EXISTS tickets_booklet_idx ON tickets (booklet_id);

CREATE TABLE IF NOT EXISTS payment_proofs (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      INTEGER     NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  archivo       TEXT        NOT NULL,   -- nombre generado en disco, nunca el original
  nombre_original TEXT      NOT NULL,
  mime          TEXT        NOT NULL,
  bytes         INTEGER     NOT NULL,
  subido_en     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS proofs_order_idx ON payment_proofs (order_id);

CREATE TABLE IF NOT EXISTS prizes (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raffle_id   INTEGER NOT NULL REFERENCES raffles (id) ON DELETE CASCADE,
  orden       INTEGER NOT NULL CHECK (orden > 0),
  nombre      TEXT    NOT NULL,
  descripcion TEXT    NOT NULL DEFAULT '',
  imagen_url  TEXT,
  UNIQUE (raffle_id, orden)
);

-- Sorteo (fase 3): se crea ahora para no migrar después
CREATE TABLE IF NOT EXISTS draws (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raffle_id        INTEGER NOT NULL REFERENCES raffles (id) ON DELETE CASCADE,
  prize_id         INTEGER NOT NULL REFERENCES prizes (id) ON DELETE CASCADE,
  ticket_id        INTEGER NOT NULL REFERENCES tickets (id),
  sorteado_por     INTEGER REFERENCES users (id) ON DELETE SET NULL,
  sorteado_en      TIMESTAMPTZ NOT NULL DEFAULT now(),
  anulado_en       TIMESTAMPTZ
);
-- Un premio solo tiene un sorteo vigente, y un número no gana dos veces
CREATE UNIQUE INDEX IF NOT EXISTS draws_prize_vigente_uq ON draws (prize_id) WHERE anulado_en IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS draws_ticket_vigente_uq ON draws (ticket_id) WHERE anulado_en IS NULL;

-- Enlaces para compradores que ya pagaron (fase 2)
CREATE TABLE IF NOT EXISTS share_links (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raffle_id INTEGER     NOT NULL REFERENCES raffles (id) ON DELETE CASCADE,
  order_id  INTEGER     REFERENCES orders (id) ON DELETE CASCADE,
  token     TEXT        NOT NULL UNIQUE,
  cupo      INTEGER     NOT NULL CHECK (cupo > 0),
  usados    INTEGER     NOT NULL DEFAULT 0 CHECK (usados >= 0 AND usados <= cupo),
  vence_en  TIMESTAMPTZ NOT NULL,
  revocado_en TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS audit_log (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raffle_id  INTEGER REFERENCES raffles (id) ON DELETE CASCADE,
  user_id    INTEGER REFERENCES users (id) ON DELETE SET NULL,
  accion     TEXT        NOT NULL,
  entidad    TEXT        NOT NULL,
  entidad_id INTEGER,
  detalle    JSONB       NOT NULL DEFAULT '{}'::jsonb,
  creado_en  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS audit_raffle_idx ON audit_log (raffle_id, creado_en DESC);
