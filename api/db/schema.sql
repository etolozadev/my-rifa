  usada_por   INTEGER     REFERENCES users (id) ON DELETE SET NULL,
  usada_en    TIMESTAMPTZ,
  revocada_en TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS invitations_raffle_idx ON invitations (raffle_id);

