-- ============================================================================
-- Personas de contacto (por rifa): a quién llamar por una venta cuando el comprador no dejó teléfono
-- (la hija que compró para su mamá, la apoderada que juntó los pedidos). Si además vendió el número
-- (rinde el dinero), la orden lo marca con contacto_vendio y aparece en su rendición.
-- ============================================================================
CREATE TABLE IF NOT EXISTS contacts (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raffle_id  INTEGER     NOT NULL REFERENCES raffles (id) ON DELETE CASCADE,
  nombre     TEXT        NOT NULL,
  telefono   TEXT        NOT NULL,
  nota       TEXT        NOT NULL DEFAULT '',
  creado_por INTEGER     REFERENCES users (id) ON DELETE SET NULL,
  creado_en  TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Un mismo teléfono no se registra dos veces en la rifa (se comparan solo los dígitos)
CREATE UNIQUE INDEX IF NOT EXISTS contacts_raffle_telefono_uq ON contacts (raffle_id, regexp_replace(telefono, '\D', '', 'g'));

-- La orden puede no tener teléfono propio si tiene persona de contacto (al menos uno de los dos)
